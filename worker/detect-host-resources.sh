#!/bin/bash
# Detect the REAL host machine's resources (CPU, RAM, disk, network, hostname, IP)
# and write them to an env file that docker compose feeds into the worker container.
#
# Why: inside Docker (especially Docker Desktop on macOS) the container only sees the
# LinuxKit VM, not the physical Mac. So RAM/CPU/disk/hostname are wrong unless we detect
# them on the host and inject them. The worker (resourceDetector.js / index.js) prefers
# these WORKER_* variables over anything it can read from inside the container.
#
# Usage: bash worker/detect-host-resources.sh [output_file]
#   output_file defaults to .worker-host.env (repo root, read by docker-compose.full.yml)

set -e

OUTPUT_FILE="${1:-.worker-host.env}"
OS="$(uname -s)"

CPU_CORES=""
RAM_GB=""
DISK_GB=""
NET_MBPS=""
HOSTNAME_VAL="$(hostname 2>/dev/null || echo "")"
IP_ADDRESS=""

echo "🔍 Detecting host resources (${OS})..."

if [ "$OS" = "Darwin" ]; then
  # --- macOS -----------------------------------------------------------------
  CPU_CORES=$(sysctl -n hw.ncpu 2>/dev/null || echo "")
  RAM_BYTES=$(sysctl -n hw.memsize 2>/dev/null || echo "")
  [ -n "$RAM_BYTES" ] && RAM_GB=$((RAM_BYTES / 1024 / 1024 / 1024))
  DISK_GB=$(df -g / 2>/dev/null | awk 'NR==2 {print $2}')

  DEFAULT_IF=$(route -n get default 2>/dev/null | awk '/interface:/{print $2}')
  if [ -n "$DEFAULT_IF" ]; then
    IP_ADDRESS=$(ipconfig getifaddr "$DEFAULT_IF" 2>/dev/null || echo "")
    # Wired link speed from the active interface media line, e.g. "1000baseT" -> 1000
    NET_MBPS=$(ifconfig "$DEFAULT_IF" 2>/dev/null \
      | awk '/media:/{print}' \
      | grep -oE '[0-9]+base' | head -1 | grep -oE '^[0-9]+' || echo "")
    # Wi-Fi: fall back to the current transmit rate (Mbps) reported by system_profiler
    if [ -z "$NET_MBPS" ]; then
      NET_MBPS=$(system_profiler SPAirPortDataType 2>/dev/null \
        | awk -F': ' '/Transmit Rate/{print $2; exit}' | grep -oE '^[0-9]+' || echo "")
    fi
  fi
  [ -z "$IP_ADDRESS" ] && IP_ADDRESS=$(ifconfig 2>/dev/null | awk '/inet /{if($2!="127.0.0.1"){print $2; exit}}')

elif [ "$OS" = "Linux" ]; then
  # --- Linux -----------------------------------------------------------------
  CPU_CORES=$(nproc 2>/dev/null || grep -c '^processor' /proc/cpuinfo 2>/dev/null || echo "")
  if [ -r /proc/meminfo ]; then
    RAM_KB=$(awk '/^MemTotal:/{print $2}' /proc/meminfo)
    [ -n "$RAM_KB" ] && RAM_GB=$((RAM_KB / 1024 / 1024))
  fi
  DISK_GB=$(df -BG / 2>/dev/null | awk 'NR==2 {gsub(/G/,"",$2); print $2}')

  DEFAULT_IF=$(ip route show default 2>/dev/null | awk '/default/{print $5; exit}')
  if [ -n "$DEFAULT_IF" ]; then
    IP_ADDRESS=$(ip -4 addr show "$DEFAULT_IF" 2>/dev/null | awk '/inet /{print $2}' | cut -d/ -f1 | head -1)
    if [ -r "/sys/class/net/$DEFAULT_IF/speed" ]; then
      SPEED=$(cat "/sys/class/net/$DEFAULT_IF/speed" 2>/dev/null || echo "")
      # virtual/down interfaces report -1; ignore those
      [ -n "$SPEED" ] && [ "$SPEED" -gt 0 ] 2>/dev/null && NET_MBPS="$SPEED"
    fi
    if [ -z "$NET_MBPS" ] && command -v ethtool >/dev/null 2>&1; then
      NET_MBPS=$(ethtool "$DEFAULT_IF" 2>/dev/null | awk -F'[ /]' '/Speed:/{print $2}' | grep -oE '^[0-9]+' || echo "")
    fi
  fi
  [ -z "$IP_ADDRESS" ] && IP_ADDRESS=$(hostname -I 2>/dev/null | awk '{print $1}')
else
  echo "⚠️  Unsupported OS '$OS' — leaving host resources undetected (worker will use container values)."
fi

# Emit the env file (only non-empty values, so the worker falls back gracefully).
{
  echo "# Auto-detected host resources — generated by worker/detect-host-resources.sh"
  echo "# DO NOT commit. Regenerate with: make detect"
  [ -n "$HOSTNAME_VAL" ] && echo "WORKER_HOSTNAME=$HOSTNAME_VAL"
  [ -n "$IP_ADDRESS" ]   && echo "WORKER_IP=$IP_ADDRESS"
  [ -n "$CPU_CORES" ]    && echo "WORKER_CPU_CORES=$CPU_CORES"
  [ -n "$RAM_GB" ]       && echo "WORKER_RAM_GB=$RAM_GB"
  [ -n "$DISK_GB" ]      && echo "WORKER_DISK_GB=$DISK_GB"
  [ -n "$NET_MBPS" ]     && echo "WORKER_NETWORK_MBPS=$NET_MBPS"
} > "$OUTPUT_FILE"

echo "✅ Wrote $OUTPUT_FILE:"
sed 's/^/   /' "$OUTPUT_FILE"
