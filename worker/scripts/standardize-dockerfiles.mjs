/**
 * Standardize every manager-service Dockerfile + Dockerfile.dev.
 *
 * Fixes two latent bugs that prevented the container images from running:
 *   1. `aerekos-record` ships a macOS (Mach-O) `better-sqlite3` prebuilt binary in
 *      its npm tarball. Inside a Linux image it fails to load ("invalid ELF header").
 *      `npm rebuild better-sqlite3` re-fetches the correct Linux prebuild (fast, no
 *      source compile needed).
 *   2. Managers `require('../shared/...')` but the old Dockerfiles never copied
 *      `worker/shared` into the image. We now COPY it to `/app/shared` and set
 *      WORKDIR to `/app/<service>` so the relative require resolves.
 *
 * Build context for every manager image is the `worker/` directory.
 *
 * Run: node worker/scripts/standardize-dockerfiles.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const workerRoot = path.join(__dirname, '..');
const portMap = require('../../conductor/api/config/managerServicePorts.js');

const containerPort = (svc) => Object.values(portMap[svc])[0];

// Some managers need extra OS packages baked into the image.
// e.g. git_manager hosts real bare repositories and serves Git Smart HTTP,
// so it needs the `git` binary present at runtime.
const EXTRA_APT = {
  git_manager: ['git'],
  compute_manager: ['git', 'docker.io'],
  // download_manager needs ffmpeg (yt-dlp mp3/muxing) + curl + ca-certificates
  // (to fetch the yt-dlp single-file binary below; ca-certificates lets curl
  // verify GitHub's TLS — the node slim base has no cert bundle by default).
  download_manager: ['ffmpeg', 'curl', 'ca-certificates'],
};

// Post-apt RUN lines for a service. download_manager bakes the yt-dlp
// STANDALONE linux binary. NOTE: the plain `yt-dlp` release asset is a Python
// zipapp (needs a python runtime, which the node slim base lacks — it exits
// 127 "python3: No such file or directory"); the self-contained ELF is
// `yt-dlp_linux`.
const EXTRA_RUN = {
  download_manager: [
    'RUN curl -fsSL https://github.com/yt-dlp/yt-dlp/releases/latest/download/yt-dlp_linux -o /usr/local/bin/yt-dlp',
    '    && chmod +x /usr/local/bin/yt-dlp',
  ],
};

const aptLine = (svc) => {
  const pkgs = EXTRA_APT[svc];
  if (!pkgs || !pkgs.length) return '';
  return `RUN apt-get update && apt-get install -y --no-install-recommends ${pkgs.join(' ')} \\
    && rm -rf /var/lib/apt/lists/*\n`;
};

const runLine = (svc) => {
  const runs = EXTRA_RUN[svc];
  if (!runs || !runs.length) return '';
  return runs.join(' \\\n') + '\n';
};

const prodDockerfile = (svc, port) => `# Generated by worker/scripts/standardize-dockerfiles.mjs — do not hand-edit.
# Build context MUST be the worker/ directory:
#   docker build -f ${svc}/Dockerfile -t aerekos-${svc} worker/
FROM node:20-bookworm-slim
WORKDIR /app/${svc}
${aptLine(svc)}${runLine(svc)}COPY ${svc}/package*.json ./
RUN npm install --omit=dev && npm cache clean --force
COPY ${svc}/ ./
# shared/ holds simplePrometheusMetrics + logOutbox used via require('../shared/..')
COPY shared /app/shared
# aerekos-record bundles a macOS better-sqlite3 binary; re-fetch the Linux prebuild.
RUN npm rebuild better-sqlite3
ENV PORT=${port}
ENV NODE_PATH=/app/${svc}/node_modules
EXPOSE ${port}
CMD ["node", "index.js"]
`;

const devDockerfile = (svc, port) => `# Generated by worker/scripts/standardize-dockerfiles.mjs — do not hand-edit.
# Build context MUST be the worker/ directory.
FROM node:20-bookworm-slim
WORKDIR /app/${svc}
${aptLine(svc)}${runLine(svc)}COPY ${svc}/package*.json ./
RUN npm install
COPY ${svc}/ ./
COPY shared /app/shared
RUN npm rebuild better-sqlite3
ENV PORT=${port} NODE_ENV=development NODE_PATH=/app/${svc}/node_modules
EXPOSE ${port}
CMD ["node", "index.js"]
`;

let written = 0;
for (const svc of Object.keys(portMap)) {
  const dir = path.join(workerRoot, svc);
  if (!fs.existsSync(dir)) {
    console.warn(`! skip ${svc}: directory not found`);
    continue;
  }
  const port = containerPort(svc);
  fs.writeFileSync(path.join(dir, 'Dockerfile'), prodDockerfile(svc, port));
  fs.writeFileSync(path.join(dir, 'Dockerfile.dev'), devDockerfile(svc, port));
  written += 1;
  console.log(`✓ ${svc} (port ${port})`);
}
console.log(`\nStandardized ${written} manager Dockerfiles + Dockerfile.dev.`);
